def _test_simple_pendulum() -> None:
    """N=1 must reduce to th'' = -(g/l) sin th."""
    c = NLinkChain(1, m=1.0, l=1.0, g=9.81)
    for th in (0.0, 0.3, 1.0, -0.7, 3.0):
        for w in (0.0, 0.5, -2.0):
            got = c.accel([th, w])[0]
            want = -(c.g / c.l) * math.sin(th)
            assert abs(got - want) < 1e-13, (th, w, got, want)
    print("  [ok] N=1 reduces to the analytic simple pendulum")


def _double_pendulum_reference(th, w, m=1.0, l=1.0, g=9.81):
    """Independently hand-written double pendulum, point masses at both joints.

    Written from the standard textbook form rather than from this module's
    general code, so agreement is a real cross-check rather than a tautology.
    """
    t0, t1 = th
    w0, w1 = w
    d = t0 - t1
    # M for two equal point masses on equal rods:
    #   [ 2 m l^2        m l^2 cos d ]
    #   [ m l^2 cos d    m l^2       ]
    M = np.array([[2.0 * m * l * l, m * l * l * math.cos(d)],
                  [m * l * l * math.cos(d), m * l * l]])
    # Centrifugal terms and gravity, standard form.
    rhs = np.array([
        -m * l * l * math.sin(d) * w1 * w1 - 2.0 * m * g * l * math.sin(t0),
        +m * l * l * math.sin(d) * w0 * w0 - 1.0 * m * g * l * math.sin(t1),
    ])
    return np.linalg.solve(M, rhs)


def _test_double_pendulum() -> None:
    c = NLinkChain(2)
    rng = np.random.default_rng(20260822)
    worst = 0.0
    for _ in range(500):
        th = rng.uniform(-2.5, 2.5, size=2)
        w = rng.uniform(-3.0, 3.0, size=2)
        state = np.empty(4)
        state[0::2], state[1::2] = th, w
        got = c.accel(state)
        want = _double_pendulum_reference(th, w)
        worst = max(worst, float(np.max(np.abs(got - want))))
    assert worst < 1e-11, f"double pendulum mismatch {worst:.3e}"
    print(f"  [ok] N=2 matches a hand-written double pendulum "
          f"(worst {worst:.2e} over 500 random states)")


def _test_coriolis_identity() -> None:
    """Check identity (2) against raw Euler-Lagrange by finite differences.

    This is the step where a derivation error would hide, so it is checked
    numerically rather than trusted. We evaluate

        sum_jk [ dM_ij/dth_k - 1/2 dM_jk/dth_i ] w_j w_k

    with central differences on M, and compare against the closed form.
    """
    rng = np.random.default_rng(7)
    for N in (2, 3, 5):
        c = NLinkChain(N)
        for _ in range(40):
            th = rng.uniform(-2.0, 2.0, size=N)
            w = rng.uniform(-2.0, 2.0, size=N)
            h = 1e-6
            dM = np.zeros((N, N, N))       # dM[i,j,k] = dM_ij / dth_k
            for k in range(N):
                tp, tm = th.copy(), th.copy()
                tp[k] += h
                tm[k] -= h
                dM[:, :, k] = (c.mass_matrix(tp) - c.mass_matrix(tm)) / (2 * h)
            brute = np.zeros(N)
            for i in range(N):
                acc = 0.0
                for j in range(N):
                    for k in range(N):
                        acc += (dM[i, j, k] - 0.5 * dM[j, k, i]) * w[j] * w[k]
                brute[i] = acc
            closed = c.coriolis(th, w)
            err = float(np.max(np.abs(brute - closed)))
            assert err < 1e-5, f"N={N} Coriolis identity failed: {err:.3e}"
    print("  [ok] Coriolis identity (2) matches finite-difference "
          "Euler-Lagrange for N=2,3,5")


def _test_small_oscillation() -> None:
    """Linearised frequencies must match the generalised eigenproblem.

    Near th=0, M -> a and the restoring term -> diag(gcoef), so the squared
    normal-mode frequencies are the eigenvalues of a^{-1} diag(gcoef).
    """
    import scipy.linalg as sla
    for N in (1, 2, 3, 4):
        c = NLinkChain(N)
        M0 = c.mass_matrix(np.zeros(N))
        K0 = np.diag(c._gcoef)
        want = np.sort(np.real(sla.eigvals(K0, M0)))
        # Recover the same thing from finite differences of accel() at rest.
        J = np.zeros((N, N))
        h = 1e-7
        for k in range(N):
            sp_, sm_ = np.zeros(2 * N), np.zeros(2 * N)
            sp_[2 * k] = +h
            sm_[2 * k] = -h
            J[:, k] = (c.accel(sp_) - c.accel(sm_)) / (2 * h)
        got = np.sort(np.real(np.linalg.eigvals(-J)))
        err = float(np.max(np.abs(got - want)))
        assert err < 1e-4, f"N={N} small-oscillation mismatch {err:.3e}"
    print("  [ok] small-oscillation frequencies match the linearised "
          "eigenproblem for N=1..4")


def _test_energy_conservation() -> None:
    """Integrate and confirm energy holds. Independent of the derivation."""
    from scipy.integrate import solve_ivp
    for N in (1, 2, 3):
        c = NLinkChain(N)
        s0 = c.default_initial_state()
        E0 = c.energy(s0)
        sol = solve_ivp(c.rhs, (0.0, 10.0), s0, method="DOP853",
                        rtol=1e-12, atol=1e-12, dense_output=False)
        assert sol.success, sol.message
        drift = max(abs(c.energy(sol.y[:, i]) - E0) / max(abs(E0), 1e-30)
                    for i in range(sol.y.shape[1]))
        assert drift < 1e-9, f"N={N} energy drift {drift:.3e}"
        print(f"  [ok] N={N} conserves energy to {drift:.2e} over 10 s")


def _test_symmetry_and_shape() -> None:
    c = NLinkChain(4)
    th = np.array([0.1, -0.4, 0.9, 0.2])
    M = c.mass_matrix(th)
    assert np.allclose(M, M.T, atol=1e-15), "mass matrix not symmetric"
    ev = np.linalg.eigvalsh(M)
    assert ev.min() > 0, f"mass matrix not positive definite: {ev}"
    print(f"  [ok] mass matrix symmetric and positive definite "
          f"(min eigenvalue {ev.min():.3f})")


def _test_canonical_consistency() -> None:
    """p_dot from p = M w must equal -dH/dq computed by finite differences.

    The Lagrangian and Hamiltonian sides of this module are derived from the
    same M, so a bug in one could hide in the other. This checks p_dot against
    an independent route: numerically differentiating H with respect to q.
    """
    rng = np.random.default_rng(99)
    for N in (1, 2, 3, 4):
        c = NLinkChain(N)
        for _ in range(25):
            th = rng.uniform(-1.5, 1.5, size=N)
            w = rng.uniform(-1.5, 1.5, size=N)
            p = c.momentum(th, w)
            qp = np.empty(2 * N)
            qp[0::2], qp[1::2] = th, p
            want = c.momentum_rate(th, w)

            # -dH/dq at fixed p, by central differences.
            got = np.zeros(N)
            h = 1e-6
            for k in range(N):
                up, dn = qp.copy(), qp.copy()
                up[2 * k] += h
                dn[2 * k] -= h
                got[k] = -(c.hamiltonian(up) - c.hamiltonian(dn)) / (2 * h)
            err = float(np.max(np.abs(got - want)))
            scale = max(1.0, float(np.max(np.abs(want))))
            assert err / scale < 1e-5, f"N={N} p_dot vs -dH/dq: {err:.3e}"
    print("  [ok] p_dot matches -dH/dq by finite differences for N=1..4")


def _test_roundtrip() -> None:
    """(q,w) -> (q,p) -> (q,w) must be the identity, and H must equal E."""
    rng = np.random.default_rng(5)
    for N in (1, 2, 3, 5):
        c = NLinkChain(N)
        for _ in range(20):
            s = np.empty(2 * N)
            s[0::2] = rng.uniform(-2, 2, size=N)
            s[1::2] = rng.uniform(-2, 2, size=N)
            qp = c.canonical_state(s)
            back = c.velocity_from_momentum(qp[0::2], qp[1::2])
            assert np.max(np.abs(back - s[1::2])) < 1e-12, "roundtrip failed"
            assert abs(c.hamiltonian(qp) - c.energy(s)) < 1e-12, "H != E"
    print("  [ok] (q,w) <-> (q,p) roundtrip exact, and H == E")


def _test_linear_systems() -> None:
    """Linear references: analytic normal modes, energy, and the eps=0 refusal."""
    import scipy.linalg as sla
    from scipy.integrate import solve_ivp

    # near_singular: det M = m^2 (2 eps - eps^2). Check the determinant law and
    # that eps = 0 is refused loudly rather than least-squared.
    # det M = 1 - (1-eps)^2 is catastrophic cancellation: the naive float
    # evaluation carries absolute error ~1e-16 regardless of eps, so by
    # eps=1e-8 the RELATIVE error is already ~5e-9 and by eps=1e-11 it is
    # ~5e-6. Test against absolute error, which is the honest bound -- and
    # note that this loss is a property of the system, not of the reference.
    # It is exactly the conditioning the axis exists to probe.
    for eps in (1e-1, 1e-3, 1e-8):
        s = near_singular_system(eps)
        want = 1.0 * (2 * eps - eps ** 2)
        assert abs(np.linalg.det(s.M) - want) < 1e-15, (eps, np.linalg.det(s.M), want)
    try:
        near_singular_system(0.0).accel(np.array([1.0, 0.0, 0.0, 0.0]))
        raise AssertionError("eps=0 should have raised SingularMassMatrix")
    except SingularMassMatrix:
        pass
    print("  [ok] near-singular determinant law holds; eps=0 refused loudly")

    # mass_ratio: frequencies must match the generalised eigenproblem, and
    # energy must hold under integration even at extreme ratios.
    for ratio in (1e0, 1e6, 1e12):
        s = mass_ratio_system(ratio)
        ev = np.sort(np.real(sla.eigvals(s.K, s.M)))
        assert np.all(ev > 0), f"ratio={ratio:g} not positive definite: {ev}"
        y0 = np.array([1.0, 0.0, 0.0, 0.0])
        E0 = s.energy(y0)
        sol = solve_ivp(s.rhs, (0.0, 20.0), y0, method="DOP853",
                        rtol=1e-12, atol=1e-12)
        assert sol.success
        drift = max(abs(s.energy(sol.y[:, i]) - E0) / abs(E0)
                    for i in range(sol.y.shape[1]))
        assert drift < 1e-8, f"ratio={ratio:g} drift {drift:.3e}"
    print("  [ok] mass-ratio modes positive and energy held to 1e-8 "
          "at ratios 1e0, 1e6, 1e12")

    # Dispatch must return the right kind of object for each portable axis.
    import systems as _sys
    got = {}
    for case in _sys.all_cases():
        r = reference_for_case(case)
        got.setdefault(case["axis"], set()).add(type(r).__name__)
    assert got.get("dof") == {"NLinkChain"}, got.get("dof")
    assert got.get("near_singular") == {"LinearSystem"}, got.get("near_singular")
    assert got.get("mass_ratio") == {"LinearSystem"}, got.get("mass_ratio")
    covered = sum(1 for c in _sys.all_cases() if reference_for_case(c) is not None)
    total = len(_sys.all_cases())
    print(f"  [ok] dispatch covers {covered}/{total} suite systems "
          f"({covered / total:.0%} of the case families)")


