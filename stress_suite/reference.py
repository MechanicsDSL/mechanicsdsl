def _test_simple_pendulum() -> None:
    """N=1 must reduce to th'' = -(g/l) sin th."""
    c = NLinkChain(1, m=1.0, l=1.0, g=9.81)
    for th in (0.0, 0.3, 1.0, -0.7, 3.0):
        for w in (0.0, 0.5, -2.0):
            got = c.accel([th, w])[0]
            want = -(c.g / c.l) * math.sin(th)
            assert abs(got - want) < 1e-13, (th, w, got, want)
    print("  [ok] N=1 reduces to the analytic simple pendulum")


def _double_pendulum_reference(th, w, m=1.0, l=1.0, g=9.81):
    """Independently hand-written double pendulum, point masses at both joints.

    Written from the standard textbook form rather than from this module's
    general code, so agreement is a real cross-check rather than a tautology.
    """
    t0, t1 = th
    w0, w1 = w
    d = t0 - t1
    # M for two equal point masses on equal rods:
    #   [ 2 m l^2        m l^2 cos d ]
    #   [ m l^2 cos d    m l^2       ]
    M = np.array([[2.0 * m * l * l, m * l * l * math.cos(d)],
                  [m * l * l * math.cos(d), m * l * l]])
    # Centrifugal terms and gravity, standard form.
    rhs = np.array([
        -m * l * l * math.sin(d) * w1 * w1 - 2.0 * m * g * l * math.sin(t0),
        +m * l * l * math.sin(d) * w0 * w0 - 1.0 * m * g * l * math.sin(t1),
    ])
    return np.linalg.solve(M, rhs)


def _test_double_pendulum() -> None:
    c = NLinkChain(2)
    rng = np.random.default_rng(20260822)
    worst = 0.0
    for _ in range(500):
        th = rng.uniform(-2.5, 2.5, size=2)
        w = rng.uniform(-3.0, 3.0, size=2)
        state = np.empty(4)
        state[0::2], state[1::2] = th, w
        got = c.accel(state)
        want = _double_pendulum_reference(th, w)
        worst = max(worst, float(np.max(np.abs(got - want))))
    assert worst < 1e-11, f"double pendulum mismatch {worst:.3e}"
    print(f"  [ok] N=2 matches a hand-written double pendulum "
          f"(worst {worst:.2e} over 500 random states)")


def _test_coriolis_identity() -> None:
    """Check identity (2) against raw Euler-Lagrange by finite differences.

    This is the step where a derivation error would hide, so it is checked
    numerically rather than trusted. We evaluate

        sum_jk [ dM_ij/dth_k - 1/2 dM_jk/dth_i ] w_j w_k

    with central differences on M, and compare against the closed form.
    """
    rng = np.random.default_rng(7)
    for N in (2, 3, 5):
        c = NLinkChain(N)
        for _ in range(40):
            th = rng.uniform(-2.0, 2.0, size=N)
            w = rng.uniform(-2.0, 2.0, size=N)
            h = 1e-6
            dM = np.zeros((N, N, N))       # dM[i,j,k] = dM_ij / dth_k
            for k in range(N):
                tp, tm = th.copy(), th.copy()
                tp[k] += h
                tm[k] -= h
                dM[:, :, k] = (c.mass_matrix(tp) - c.mass_matrix(tm)) / (2 * h)
            brute = np.zeros(N)
            for i in range(N):
                acc = 0.0
                for j in range(N):
                    for k in range(N):
                        acc += (dM[i, j, k] - 0.5 * dM[j, k, i]) * w[j] * w[k]
                brute[i] = acc
            closed = c.coriolis(th, w)
            err = float(np.max(np.abs(brute - closed)))
            assert err < 1e-5, f"N={N} Coriolis identity failed: {err:.3e}"
    print("  [ok] Coriolis identity (2) matches finite-difference "
          "Euler-Lagrange for N=2,3,5")


def _test_small_oscillation() -> None:
    """Linearised frequencies must match the generalised eigenproblem.

    Near th=0, M -> a and the restoring term -> diag(gcoef), so the squared
    normal-mode frequencies are the eigenvalues of a^{-1} diag(gcoef).
    """
    import scipy.linalg as sla
    for N in (1, 2, 3, 4):
        c = NLinkChain(N)
        M0 = c.mass_matrix(np.zeros(N))
        K0 = np.diag(c._gcoef)
        want = np.sort(np.real(sla.eigvals(K0, M0)))
        # Recover the same thing from finite differences of accel() at rest.
        J = np.zeros((N, N))
        h = 1e-7
        for k in range(N):
            sp_, sm_ = np.zeros(2 * N), np.zeros(2 * N)
            sp_[2 * k] = +h
            sm_[2 * k] = -h
            J[:, k] = (c.accel(sp_) - c.accel(sm_)) / (2 * h)
        got = np.sort(np.real(np.linalg.eigvals(-J)))
        err = float(np.max(np.abs(got - want)))
        assert err < 1e-4, f"N={N} small-oscillation mismatch {err:.3e}"
    print("  [ok] small-oscillation frequencies match the linearised "
          "eigenproblem for N=1..4")


def _test_energy_conservation() -> None:
    """Integrate and confirm energy holds. Independent of the derivation."""
    from scipy.integrate import solve_ivp
    for N in (1, 2, 3):
        c = NLinkChain(N)
        s0 = c.default_initial_state()
        E0 = c.energy(s0)
        sol = solve_ivp(c.rhs, (0.0, 10.0), s0, method="DOP853",
                        rtol=1e-12, atol=1e-12, dense_output=False)
        assert sol.success, sol.message
        drift = max(abs(c.energy(sol.y[:, i]) - E0) / max(abs(E0), 1e-30)
                    for i in range(sol.y.shape[1]))
        assert drift < 1e-9, f"N={N} energy drift {drift:.3e}"
        print(f"  [ok] N={N} conserves energy to {drift:.2e} over 10 s")


def _test_symmetry_and_shape() -> None:
    c = NLinkChain(4)
    th = np.array([0.1, -0.4, 0.9, 0.2])
    M = c.mass_matrix(th)
    assert np.allclose(M, M.T, atol=1e-15), "mass matrix not symmetric"
    ev = np.linalg.eigvalsh(M)
    assert ev.min() > 0, f"mass matrix not positive definite: {ev}"
    print(f"  [ok] mass matrix symmetric and positive definite "
          f"(min eigenvalue {ev.min():.3f})")


def main() -> int:
    print("reference.py self-tests -- planar N-link chain\n")
    _test_simple_pendulum()
    _test_double_pendulum()
    _test_coriolis_identity()
    _test_symmetry_and_shape()
    _test_small_oscillation()
    _test_energy_conservation()
    print("\nAll self-tests passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
