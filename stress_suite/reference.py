"""
Library-independent ground truth for the planar N-link pendulum chain.

WHY THIS EXISTS
---------------
The suite already has an oracle in `groundtruth.py`, built on
`sympy.physics.mechanics.LagrangesMethod`. That is a genuinely separate
derivation path from MechanicsDSL, and it is adequate for adjudicating
MechanicsDSL. It is NOT adequate once SymPy itself becomes one of the engines
under test: a hand-rolled SymPy derivation checked against SymPy's own
`LagrangesMethod` shares `diff`, `simplify`, `solve`, and the assumptions
machinery beneath them. Agreement under those conditions is closer to a
self-consistency check than to independent confirmation, and it would leave the
three columns of the comparison table resting on evidence of different
strengths -- the one defect a comparison table cannot survive.

This module derives the same equations of motion with NO symbolic algebra at
all. It shares no library with any engine under test; it needs only numpy for
linear algebra. It is therefore a valid referee for all three columns.

It also closes a coverage gap. The symbolic oracle only applies to the
unconstrained Lagrangian pathway, leaving 33 of the suite's 55 cases (60%) with
no independent derivation check. Because this reference produces accelerations
directly from the state, it adjudicates any pathway that can be asked for an
acceleration -- including the Hamiltonian one.

THE DERIVATION
--------------
The suite's `n_pendulum_dsl(N)` builds N point masses, each of mass m, joined
by massless rods of length l, all angles measured from the downward vertical.
Its Lagrangian is

    T = 1/2 * sum_{j,k} a_jk * cos(th_j - th_k) * w_j * w_k
    V = sum_j (N - j) * m * g * l * (1 - cos th_j)

    where a_jk = (N - max(j, k)) * m * l**2      and  w = dth/dt

so the mass matrix is read off directly:

    M_ij(th) = a_ij * cos(th_i - th_j)                                   (1)

For a Lagrangian of the form L = 1/2 w^T M(th) w - V(th), Euler-Lagrange gives

    sum_j M_ij a_j + sum_jk [ dM_ij/dth_k - 1/2 dM_jk/dth_i ] w_j w_k
                                                       + dV/dth_i = 0

Substituting (1) and using dM_ij/dth_k = -a_ij sin(th_i - th_j) (d_ik - d_jk),
the bracketed double sum collapses -- the cross terms cancel exactly -- to a
single sum of squared velocities:

    C_i(th, w) = sum_j a_ij * sin(th_i - th_j) * w_j**2                  (2)

This cancellation is the reason the N-link chain has a closed form worth
writing by hand, and it is verified numerically in `_test_coriolis_identity`
against a finite-difference evaluation of the raw Euler-Lagrange expression,
so the algebra above is checked rather than trusted.

Gravity is immediate:

    G_i(th) = (N - i) * m * g * l * sin(th_i)                            (3)

and the equation of motion is

    M(th) a + C(th, w) + G(th) = 0   =>   a = -M(th)^{-1} (C + G)        (4)

STATE LAYOUT
------------
[th_0, w_0, th_1, w_1, ...] -- interleaved, matching what MechanicsDSL's solver
and `worker.py` already use, so no reordering is needed at the call site.

VALIDATION
----------
Run this file directly to execute the self-tests:

    python reference.py

They check, in order: the N=1 simple pendulum against its analytic form; the
N=2 case against an independently hand-written double pendulum; the Coriolis
identity (2) against finite differences of the Lagrangian; small-oscillation
frequencies against the eigenvalues of the linearised system; and energy
conservation under integration.
"""

from __future__ import annotations

import math
from typing import Optional

import numpy as np

__all__ = ["NLinkChain", "chain_for_case"]


class NLinkChain:
    """Planar N-link pendulum: point masses, massless rods, equal m and l.

    Matches the system generated by `systems.n_pendulum_dsl(N)`.
    """

    def __init__(self, N: int, m: float = 1.0, l: float = 1.0,
                 g: float = 9.81) -> None:
        if N < 1:
            raise ValueError(f"N must be >= 1, got {N}")
        self.N = int(N)
        self.m = float(m)
        self.l = float(l)
        self.g = float(g)

        # a_ij = (N - max(i,j)) * m * l^2. Constant in time, so build it once.
        idx = np.arange(self.N)
        self._a = (self.N - np.maximum.outer(idx, idx)) * self.m * self.l ** 2

        # Gravity coefficient (N - i) * m * g * l, likewise constant.
        self._gcoef = (self.N - idx) * self.m * self.g * self.l

    # -- pieces of the equation of motion -----------------------------------

    def mass_matrix(self, th: np.ndarray) -> np.ndarray:
        """M_ij = a_ij cos(th_i - th_j).  Symmetric, positive definite."""
        th = np.asarray(th, dtype=float)
        return self._a * np.cos(th[:, None] - th[None, :])

    def coriolis(self, th: np.ndarray, w: np.ndarray) -> np.ndarray:
        """C_i = sum_j a_ij sin(th_i - th_j) w_j^2.   See identity (2)."""
        th = np.asarray(th, dtype=float)
        w = np.asarray(w, dtype=float)
        return (self._a * np.sin(th[:, None] - th[None, :])) @ (w ** 2)

    def gravity(self, th: np.ndarray) -> np.ndarray:
        """G_i = (N - i) m g l sin(th_i)."""
        return self._gcoef * np.sin(np.asarray(th, dtype=float))

    # -- the oracle interface ------------------------------------------------

    def accel(self, state: np.ndarray) -> np.ndarray:
        """Angular accelerations at an interleaved state [th0, w0, th1, w1, ...].

        Solves M a = -(C + G) numerically. The mass matrix is never inverted
        symbolically -- that is precisely the step that blows up in the engines
        under test, and doing it here would import their scaling problem into
        the referee.
        """
        th, w = self.split(state)
        M = self.mass_matrix(th)
        rhs = -(self.coriolis(th, w) + self.gravity(th))
        try:
            return np.linalg.solve(M, rhs)
        except np.linalg.LinAlgError:
            # Genuinely singular M. Report rather than silently least-squares
            # it -- substituting a well-defined answer to a different question
            # is the exact failure mode this study measures.
            raise SingularMassMatrix(
                f"mass matrix singular at th={th.tolist()}; "
                f"cond={np.linalg.cond(M):.3e}"
            ) from None

    def rhs(self, _t: float, state: np.ndarray) -> np.ndarray:
        """ODE right-hand side, for handing to an integrator."""
        th, w = self.split(state)
        a = self.accel(state)
        out = np.empty(2 * self.N, dtype=float)
        out[0::2] = w
        out[1::2] = a
        return out

    # -- diagnostics ---------------------------------------------------------

    def energy(self, state: np.ndarray) -> float:
        """Total energy T + V. Conserved for this system; an oracle in itself."""
        th, w = self.split(state)
        T = 0.5 * float(w @ self.mass_matrix(th) @ w)
        V = float(np.sum(self._gcoef * (1.0 - np.cos(th))))
        return T + V

    def condition_number(self, th: np.ndarray) -> float:
        return float(np.linalg.cond(self.mass_matrix(th)))

    def split(self, state: np.ndarray):
        """Interleaved state -> (angles, velocities)."""
        s = np.asarray(state, dtype=float)
        if s.shape != (2 * self.N,):
            raise ValueError(
                f"state must have shape ({2 * self.N},) for N={self.N}, "
                f"got {s.shape}")
        return s[0::2].copy(), s[1::2].copy()

    def default_initial_state(self) -> np.ndarray:
        """The initial conditions `n_pendulum_dsl` writes: th0=0.3, rest 0.15."""
        s = np.zeros(2 * self.N, dtype=float)
        s[0::2] = np.where(np.arange(self.N) == 0, 0.3, 0.15)
        return s

    def __repr__(self) -> str:
        return (f"NLinkChain(N={self.N}, m={self.m}, l={self.l}, g={self.g})")


class SingularMassMatrix(RuntimeError):
    """Raised when M(th) cannot be solved. Loud by design."""


def chain_for_case(case: dict) -> Optional[NLinkChain]:
    """Build a reference for a suite case, or None if this family doesn't apply.

    Only the `dof` axis is the plain equal-parameter N-link chain. The other
    axes perturb masses or add constraints and need their own references (or
    none).
    """
    if case.get("axis") != "dof":
        return None
    return NLinkChain(int(case["knob"]))


